"""
RL training on HotpotQA for reasoning+answer traces.

Supports:
  - GRPO (group-normalized policy gradient with KL regularization)
  - CISPO (clipped importance objective with KL regularization)

Reward:
  - format reward: 0/1 for presence/order of <think>, [answer_start], [answer_end]
  - exact-match reward: 0/1 against HotpotQA gold answer
  - total = format_weight * format + em_weight * em
"""

